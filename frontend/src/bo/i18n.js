const isObject = (v) => v && typeof v === "object" && !Array.isArray(v);

function merge(fallback, messages) {
  const out = { ...fallback };
  for (const [k, v] of Object.entries(messages)) out[k] = isObject(v) && isObject(fallback[k]) ? merge(fallback[k], v) : v;
  return out;
}

const italianMessages = merge(englishMessages, italian);

const i18nProvider = polyglotI18nProvider(() => italianMessages, "it", [{ locale: "it", name: "Italiano" }], {
  allowMissing: true,
});

export default i18nProvider;
